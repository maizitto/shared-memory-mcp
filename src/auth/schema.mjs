/** Additive OAuth state. The fact ledger and owner-review sessions are unchanged. */
export const OAUTH_SCHEMA = [
`CREATE TABLE IF NOT EXISTS memory_oauth_connections (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL, client_id TEXT NOT NULL, resource TEXT NOT NULL,
 scope TEXT NOT NULL, redirect_origin TEXT NOT NULL,
 collections_json TEXT NOT NULL CHECK(json_valid(collections_json) AND json_type(collections_json)='array'),
 status TEXT NOT NULL CHECK(status IN ('pending','active','revoked')), provider_grant_id TEXT,
 created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL, expires_at INTEGER NOT NULL, revoked_at INTEGER)`,
`CREATE INDEX IF NOT EXISTS memory_oauth_owner ON memory_oauth_connections(user_id,status)`,
`CREATE TABLE IF NOT EXISTS memory_oauth_uses (
 kind TEXT NOT NULL, digest TEXT NOT NULL, expires_at INTEGER NOT NULL, PRIMARY KEY(kind,digest))`,
`CREATE INDEX IF NOT EXISTS memory_oauth_uses_expiry ON memory_oauth_uses(expires_at)`,
`CREATE TABLE IF NOT EXISTS memory_oauth_budgets (
 bucket TEXT NOT NULL CHECK(bucket IN ('consent','token','register')), day TEXT NOT NULL,
 used INTEGER NOT NULL, PRIMARY KEY(bucket,day))`
];
export async function installOAuthSchema(db) { for (const sql of OAUTH_SCHEMA) await db.prepare(sql).run(); }
export const oauthMigrationSql = () => '-- Additive OAuth metadata. Generated by npm run schema; apply explicitly.\n\n'
  + OAUTH_SCHEMA.map(sql => sql.replace(' IF NOT EXISTS ', ' ') + ';').join('\n\n') + '\n';
