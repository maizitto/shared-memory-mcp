import { SCHEMA } from '../schema.mjs';
import { RETENTION_SCHEMA } from '../retention.mjs';
/** Review-session tables. Separate from the fact ledger so that review state never becomes memory content. */
export const REVIEW_SCHEMA = [
`CREATE TABLE IF NOT EXISTS memory_review_logins (
 state_sha256 TEXT PRIMARY KEY, binding_sha256 TEXT NOT NULL, verifier TEXT NOT NULL,
 created_at_ms INTEGER NOT NULL, expires_at_ms INTEGER NOT NULL, used_at_ms INTEGER)`,
`CREATE TABLE IF NOT EXISTS memory_review_sessions (
 token_sha256 TEXT PRIMARY KEY, github_id TEXT NOT NULL,
 created_at_ms INTEGER NOT NULL, expires_at_ms INTEGER NOT NULL, revoked_at_ms INTEGER)`,
`CREATE TABLE IF NOT EXISTS memory_review_budget (day TEXT PRIMARY KEY, used INTEGER NOT NULL)`,
];
/** Bearer clients of the opt-in /memory/mcp endpoint. Only SHA-256 digests of tokens are stored. */
export const CLIENT_SCHEMA = [
`CREATE TABLE IF NOT EXISTS memory_clients (
 id TEXT PRIMARY KEY, label TEXT NOT NULL, token_sha256 TEXT NOT NULL UNIQUE,
 scopes TEXT NOT NULL, created_at_ms INTEGER NOT NULL, revoked_at_ms INTEGER)`,
];
/** Which collections each bearer client may read or propose to. The client's own scopes remain the ceiling. */
export const GRANT_SCHEMA = [
`CREATE TABLE IF NOT EXISTS memory_client_grants (
 client_id TEXT NOT NULL REFERENCES memory_clients(id), collection_id TEXT NOT NULL, scopes TEXT NOT NULL,
 PRIMARY KEY(client_id,collection_id))`,
];
export async function installReviewSchema(db) { for (const sql of [...REVIEW_SCHEMA, ...CLIENT_SCHEMA, ...GRANT_SCHEMA, ...RETENTION_SCHEMA]) await db.prepare(sql).run(); }
/** One-off D1 migration. Without IF NOT EXISTS it fails instead of silently adopting a same-named table. */
export const migrationSql = () => '-- Generated by migrationSql() in integrations/shared-memory/review/schema.mjs. Do not edit by hand.\n\n' +
  [...SCHEMA, ...REVIEW_SCHEMA, ...CLIENT_SCHEMA].map(sql => `${sql.replace(' IF NOT EXISTS ', ' ')};`).join('\n\n') + '\n';
/** Second migration: grants and purge audit. Existing clients keep exactly their former access to `synthetic`. */
export const migration2Sql = () => '-- Generated by migration2Sql() in integrations/shared-memory/review/schema.mjs. Do not edit by hand.\n\n' +
  [...GRANT_SCHEMA, ...RETENTION_SCHEMA].map(sql => `${sql.replace(' IF NOT EXISTS ', ' ')};`).join('\n\n') +
  "\n\nINSERT INTO memory_client_grants(client_id,collection_id,scopes) SELECT id,'synthetic',scopes FROM memory_clients;\n";
