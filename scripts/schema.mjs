import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { SCHEMA } from '../src/memory/schema.mjs';
import { LEXICAL_SCHEMA } from '../src/memory/lexical-schema.mjs';
import { REVIEW_SCHEMA, CLIENT_SCHEMA, GRANT_SCHEMA } from '../src/memory/review/schema.mjs';
import { RETENTION_SCHEMA } from '../src/memory/retention.mjs';
import { oauthMigrationSql } from '../src/auth/schema.mjs';

const sql = '-- Fresh-install schema. Generated by npm run schema; never apply to an existing installation.\n\n'
  + [...SCHEMA, ...LEXICAL_SCHEMA, ...REVIEW_SCHEMA, ...CLIENT_SCHEMA, ...GRANT_SCHEMA, ...RETENTION_SCHEMA]
    .map(statement => statement.replace(' IF NOT EXISTS ', ' ') + ';').join('\n\n') + '\n';
const path = new URL('../migrations/0001_bootstrap.sql', import.meta.url);
const oauthPath = new URL('../migrations/0002_oauth.sql', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== sql) throw new Error('Bootstrap schema drift.');
  if (await readFile(oauthPath, 'utf8') !== oauthMigrationSql()) throw new Error('OAuth schema drift.');
} else {
  await mkdir(new URL('../migrations/', import.meta.url), { recursive: true });
  await writeFile(path, sql);
  await writeFile(oauthPath, oauthMigrationSql());
  console.log('Generated migrations/0001_bootstrap.sql and migrations/0002_oauth.sql');
}
